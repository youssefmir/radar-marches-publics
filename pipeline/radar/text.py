_TOKEN = re.compile(r"[a-z0-9]+")


def strip_accents(s: str) -> str:
    return "".join(c for c in unicodedata.normalize("NFKD", s) if not unicodedata.combining(c))


def stem(tok: str) -> str:
    """Racinisation légère : pluriels et quelques suffixes fréquents (suffisant pour BM25)."""
    for suf in (
        "ements",
        "ement",
        "ations",
        "ation",
        "iques",
        "ique",
        "euses",
        "euse",
        "eurs",
        "eur",
        "es",
        "s",
        "x",
        "e",
    ):
        if tok.endswith(suf) and len(tok) - len(suf) >= 4:
            return tok[: -len(suf)]
    return tok


def tokenize(text: str | None) -> list[str]:
    if not text:
        return []
    toks = _TOKEN.findall(strip_accents(text.lower()))
    return [stem(t) for t in toks if t not in STOPWORDS and len(t) > 1 and not t.isdigit()]
